--
-- 관리자 화면에서 쓰는 서버 함수와 테이블. 모든 함수는 안에서 관리자인지(is_admin) 다시 확인한다.
--   ADMIN-01 대시보드        admin_dashboard()
--   ADMIN-02/03 신고 관리     admin_list_reports(), admin_update_report()  → 답변은 사용자 신고 내역에도 보인다
--   ADMIN-04 리워드 모니터링  admin_list_point_activity(), admin_list_checkins(), admin_review_checkin()
--   ADMIN-05 회원 관리        admin_list_members(), admin_set_member_role() (013)
--   ADMIN-06 흡연시설 관리    admin_update_facility()
--   ADMIN-07 가상 후원 예산   sponsors, sponsor_transactions, admin_list_sponsors(), admin_save_sponsor(), admin_adjust_sponsor_budget()
-- 관리자가 바꾼 내용은 admin_actions에 남긴다 (처리 이력, 변경 이력, 예산 조정 이력).
--
-- ⚠️ 후원 기업과 예산은 실제 협찬이 아닌 가상 시뮬레이션이다. 포인트가 적립되면 진행 중인 가상 기업 예산에서 차감된 것으로 기록만 한다.

-- 1) 관리자 처리 기록 ------------------------------------------------------------
create table public.admin_actions (
  id          bigint generated by default as identity primary key,
  admin_id    uuid references public.users (id) on delete set null,
  action      text not null,          -- report_update, facility_update, checkin_review, sponsor_save, sponsor_budget
  target_type text not null,          -- report, facility, checkin, sponsor
  target_id   text not null,
  detail      jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index admin_actions_target_idx on public.admin_actions (target_type, target_id, created_at desc);

alter table public.admin_actions enable row level security;
create policy "admin_actions: 관리자 조회" on public.admin_actions
  for select to authenticated using (public.is_admin());
revoke insert, update, delete on public.admin_actions from anon, authenticated;

