  add column reviewed_at   timestamptz;

-- 4) 가상 후원 기업·예산 ----------------------------------------------------------
create table public.sponsors (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 40),
  description text not null default '' check (char_length(description) <= 300),
  starts_on   date not null,
  ends_on     date not null,
  created_at  timestamptz not null default now(),
  check (ends_on >= starts_on)
);

create table public.sponsor_transactions (
  id          bigint generated by default as identity primary key,
  sponsor_id  bigint not null references public.sponsors (id) on delete cascade,
  kind        text not null check (kind in ('budget', 'payout')),  -- budget: 예산 추가(+)/조정(-), payout: 포인트 지급
  amount      integer not null check (amount <> 0),
  note        text not null default '' check (char_length(note) <= 200),
  point_id    bigint unique references public.point_ledger (id) on delete set null,
  created_by  uuid references public.users (id) on delete set null,
  created_at  timestamptz not null default now()
);
create index sponsor_transactions_sponsor_idx on public.sponsor_transactions (sponsor_id, created_at desc);

alter table public.sponsors enable row level security;
alter table public.sponsor_transactions enable row level security;
create policy "sponsors: 관리자 조회" on public.sponsors for select to authenticated using (public.is_admin());
create policy "sponsor_transactions: 관리자 조회" on public.sponsor_transactions for select to authenticated using (public.is_admin());
revoke insert, update, delete on public.sponsors, public.sponsor_transactions from anon, authenticated;

-- 포인트가 적립되면 진행 중이고 잔여 예산이 충분한 가상 기업 중 종료일이 가장 이른 곳에서 차감한 것으로 기록한다
create function public.charge_sponsor_for_points()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_sponsor bigint;
  today date := (now() at time zone 'Asia/Seoul')::date;
begin
  if new.amount <= 0 then
    return new;
  end if;
  select s.id into v_sponsor
  from public.sponsors s
  where today between s.starts_on and s.ends_on
    and (select coalesce(sum(t.amount), 0) from public.sponsor_transactions t where t.sponsor_id = s.id
         and t.kind = 'budget')
      - (select coalesce(sum(t.amount), 0) from public.sponsor_transactions t where t.sponsor_id = s.id
         and t.kind = 'payout') >= new.amount
  order by s.ends_on, s.id
  limit 1;

  if v_sponsor is not null then
    insert into public.sponsor_transactions (sponsor_id, kind, amount, note, point_id)
    values (v_sponsor, 'payout', new.amount, new.reason, new.id);
  end if;
  return new;
end;
$$;
revoke execute on function public.charge_sponsor_for_points() from public, anon, authenticated;

create trigger point_ledger_charge_sponsor
  after insert on public.point_ledger
  for each row execute function public.charge_sponsor_for_points();

-- 5) ADMIN-01 대시보드 -------------------------------------------------------------
create function public.admin_dashboard()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  today date := (now() at time zone 'Asia/Seoul')::date;
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 볼 수 있어요.' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'total_users',        (select count(*) from public.users),
    'admin_users',        (select count(*) from public.users where is_admin),
    'today_reports',      (select count(*) from public.reports where (created_at at time zone 'Asia/Seoul')::date = today),
    'unresolved_reports', (select count(*) from public.reports where status in ('received', 'reviewing')),
    'today_points',       (select coalesce(sum(amount), 0) from public.point_ledger where (created_at at time zone 'Asia/Seoul')::date = today),
    'today_checkins',     (select count(*) from public.facility_checkins where checkin_date = today),
    'suspicious_checkins', (select count(*) from public.admin_list_checkins() c where c.flagged and c.review_status = 'none'),
    'low_budget_sponsors', (select count(*) from public.admin_list_sponsors() s where s.active and s.budget > 0 and s.remaining < s.budget * 0.2),
    'recent_reports', coalesce((
      select jsonb_agg(r order by r.created_at desc)
      from (
        select rp.id, rp.type, rp.status, rp.created_at, f.name as facility_name, u.nickname
        from public.reports rp
        join public.smoking_facilities f on f.id = rp.facility_id
        left join public.users u on u.id = rp.user_id
        order by rp.created_at desc
        limit 5
      ) r), '[]'::jsonb)
  );
end;
$$;

