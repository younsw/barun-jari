-- 상태 변경 + 답변. 반영(accepted)으로 바뀌면 004/012 트리거가 신고자에게 포인트를 준다.
create function public.admin_update_report(p_report_id bigint, p_status text, p_reply text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  before record;
  reply text := nullif(left(trim(coalesce(p_reply, '')), 500), '');
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 처리할 수 있어요.' using errcode = '42501';
  end if;
  if p_status not in ('received', 'reviewing', 'accepted', 'rejected') then
    raise exception 'admin: 처리 상태를 확인해 주세요.' using errcode = '22023';
  end if;
  select r.status, r.admin_reply into before from public.reports r where r.id = p_report_id for update;
  if not found then
    raise exception 'admin: 신고를 찾을 수 없어요.' using errcode = 'P0002';
  end if;
  if before.status = 'accepted' and p_status <> 'accepted' then
    raise exception 'admin: 이미 반영돼 포인트가 지급된 신고는 상태를 되돌릴 수 없어요.' using errcode = 'P0001';
  end if;
  if p_status = 'rejected' and reply is null then
    raise exception 'admin: 반려할 때는 사용자에게 안내할 답변을 적어 주세요.' using errcode = '22023';
  end if;

  update public.reports
  set status = p_status, admin_reply = reply, handled_by = auth.uid(), handled_at = now()
  where id = p_report_id;

  insert into public.admin_actions (admin_id, action, target_type, target_id, detail)
  values (auth.uid(), 'report_update', 'report', p_report_id::text,
    jsonb_build_object('from', before.status, 'to', p_status, 'reply', reply));
end;
$$;

-- 7) ADMIN-04 리워드 모니터링 -------------------------------------------------------
create function public.admin_list_point_activity(p_days integer default 7)
returns table (id bigint, user_id uuid, nickname text, amount integer, reason text, ref_id text, created_at timestamptz, sponsor_name text)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 볼 수 있어요.' using errcode = '42501';
  end if;
  return query
    select p.id, p.user_id, u.nickname, p.amount, p.reason, p.ref_id, p.created_at, s.name
    from public.point_ledger p
    left join public.users u on u.id = p.user_id
    left join public.sponsor_transactions t on t.point_id = p.id
    left join public.sponsors s on s.id = t.sponsor_id
    where p.created_at >= now() - make_interval(days => greatest(1, least(coalesce(p_days, 7), 90)))
    order by p.created_at desc;
end;
$$;

-- 의심 기준: 같은 회원이 직전 인증 후 10분 안에 다시 인증(짧은 시간 반복),
--            같은 장소를 최근 7일 중 3일 이상 인증(동일 장소 반복)
create function public.admin_list_checkins()
returns table (
  id bigint, user_id uuid, nickname text, facility_id bigint, facility_name text, photo_path text,
  distance_m real, location_accuracy_m real, points_awarded integer, created_at timestamptz,
  quick_repeat boolean, same_place_days integer, flagged boolean,
  review_status text, review_note text, reviewed_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 볼 수 있어요.' using errcode = '42501';
  end if;
  return query
    with base as (
      select c.*,
        lag(c.created_at) over (partition by c.user_id order by c.created_at) as prev_at,
        (select count(distinct c2.checkin_date)::integer from public.facility_checkins c2
          where c2.user_id = c.user_id and c2.facility_id = c.facility_id
            and c2.checkin_date between c.checkin_date - 6 and c.checkin_date) as place_days
      from public.facility_checkins c
    )
    select b.id, b.user_id, u.nickname, b.facility_id, f.name, b.photo_path,
      b.distance_m, b.location_accuracy_m, b.points_awarded, b.created_at,
      coalesce(b.created_at - b.prev_at < interval '10 minutes', false),
      b.place_days,
      coalesce(b.created_at - b.prev_at < interval '10 minutes', false) or b.place_days >= 3,
      b.review_status, b.review_note, b.reviewed_at
    from base b
    join public.smoking_facilities f on f.id = b.facility_id
    left join public.users u on u.id = b.user_id
    order by b.created_at desc;
end;
$$;

create function public.admin_review_checkin(p_checkin_id bigint, p_status text, p_note text)
returns void
language plpgsql
