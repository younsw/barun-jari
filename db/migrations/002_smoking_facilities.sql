-- 002: 흡연시설 (공공데이터, 누구나 조회 가능)

create table public.smoking_facilities (
  id         bigint generated by default as identity primary key,
  district   text    not null,                 -- 자치구 (예: 중랑구)
  category   text    not null,                 -- 업종 (게임업소, 체육시설업 ...)
  name       text    not null,                 -- 시설명(업소)
  address    text    not null,
  room_count integer not null default 1 check (room_count > 0),
  latitude   double precision,                 -- 지오코딩 후 채움
  longitude  double precision,
  created_at timestamptz not null default now(),
  unique (name, address)
);

create index smoking_facilities_district_idx on public.smoking_facilities (district);
create index smoking_facilities_category_idx on public.smoking_facilities (category);
create index smoking_facilities_location_idx on public.smoking_facilities (latitude, longitude);

-- 권한: 조회는 누구나, 수정은 서버(service role)만
alter table public.smoking_facilities enable row level security;

create policy "facilities: 누구나 조회" on public.smoking_facilities
  for select to anon, authenticated
  using (true);
