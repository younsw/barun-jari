-- 004: 리워드 포인트
-- 규칙: 하루(한국 시간) 최대 10포인트, 같은 ref_id는 한 번만 적립,
--       신고가 accepted가 되면 +3포인트

create table public.point_ledger (
  id         bigint generated by default as identity primary key,
  user_id    uuid    not null references public.users (id) on delete cascade,
  amount     integer not null check (amount > 0),
  reason     text    not null,                 -- 예: report_accepted, attendance
  ref_id     text,                             -- 예: report:12 (중복 적립 방지)
  created_at timestamptz not null default now(),
  unique (user_id, ref_id)
);

create index point_ledger_user_idx on public.point_ledger (user_id, created_at desc);

-- 포인트 적립. 실제로 적립된 포인트를 돌려줍니다 (한도 초과·중복이면 0).
-- 화면에서 직접 부를 수 없고, 트리거나 서버(service role)에서만 호출합니다.
create function public.award_points(p_user_id uuid, p_amount integer, p_reason text, p_ref_id text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  daily_limit constant integer := 10;
  today_sum integer;
  granted integer;
begin
  -- 같은 사용자의 동시 적립을 순서대로 처리
  perform pg_advisory_xact_lock(hashtext('points:' || p_user_id::text));

  if p_ref_id is not null and exists (
    select 1 from point_ledger where user_id = p_user_id and ref_id = p_ref_id
  ) then
    return 0;
  end if;

  select coalesce(sum(amount), 0) into today_sum
  from point_ledger
  where user_id = p_user_id
    and (created_at at time zone 'Asia/Seoul')::date = (now() at time zone 'Asia/Seoul')::date;

  granted := least(p_amount, daily_limit - today_sum);
  if granted <= 0 then
    return 0;
  end if;

  insert into point_ledger (user_id, amount, reason, ref_id)
  values (p_user_id, granted, p_reason, p_ref_id);
  return granted;
end;
$$;

revoke execute on function public.award_points(uuid, integer, text, text) from public, anon, authenticated;

-- 신고가 accepted로 바뀌면 신고자에게 +3
create function public.reward_accepted_report()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'accepted' and old.status is distinct from 'accepted' then
    perform award_points(new.user_id, 3, 'report_accepted', 'report:' || new.id);
  end if;
  return new;
end;
$$;

create trigger reports_reward_on_accept
  after update of status on public.reports
  for each row execute function public.reward_accepted_report();

-- 내 포인트 요약 (화면용)
create function public.get_my_point_summary()
returns table (total integer, today integer, daily_limit integer)
language sql
stable
security definer
set search_path = public
as $$
  select
    coalesce(sum(amount), 0)::integer,
    coalesce(sum(amount) filter (
      where (created_at at time zone 'Asia/Seoul')::date = (now() at time zone 'Asia/Seoul')::date
    ), 0)::integer,
    10
  from point_ledger
  where user_id = auth.uid();
$$;

-- 권한: 내 내역만 보기, 직접 추가·수정·삭제 불가
alter table public.point_ledger enable row level security;

create policy "points: 내 내역 보기" on public.point_ledger
  for select to authenticated
  using (user_id = auth.uid());
