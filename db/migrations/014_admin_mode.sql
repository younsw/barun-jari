-- 8) ADMIN-06 흡연시설 정보 수정 ------------------------------------------------------
create function public.admin_update_facility(
  p_facility_id bigint, p_name text, p_address text, p_category text, p_room_count integer,
  p_latitude double precision, p_longitude double precision
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  before record;
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 수정할 수 있어요.' using errcode = '42501';
  end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_address), '') = '' or coalesce(trim(p_category), '') = '' then
    raise exception 'admin: 시설명, 주소, 업종을 모두 입력해 주세요.' using errcode = '22023';
  end if;
  if p_room_count is null or p_room_count < 1 then
    raise exception 'admin: 부스 수는 1 이상이어야 해요.' using errcode = '22023';
  end if;
  if (p_latitude is null) <> (p_longitude is null)
     or p_latitude not between 33 and 39 or p_longitude not between 124 and 132 then
    raise exception 'admin: 위도·경도를 확인해 주세요 (한국 범위, 둘 다 입력하거나 둘 다 비우기).' using errcode = '22023';
  end if;

  select f.name, f.address, f.category, f.room_count, f.latitude, f.longitude into before
  from public.smoking_facilities f where f.id = p_facility_id for update;
  if not found then
    raise exception 'admin: 시설을 찾을 수 없어요.' using errcode = 'P0002';
  end if;

  update public.smoking_facilities
  set name = trim(p_name), address = trim(p_address), category = trim(p_category), room_count = p_room_count,
      latitude = p_latitude, longitude = p_longitude
  where id = p_facility_id;

  insert into public.admin_actions (admin_id, action, target_type, target_id, detail)
  values (auth.uid(), 'facility_update', 'facility', p_facility_id::text, jsonb_build_object(
    'before', jsonb_build_object('name', before.name, 'address', before.address, 'category', before.category,
      'room_count', before.room_count, 'latitude', before.latitude, 'longitude', before.longitude),
    'after', jsonb_build_object('name', trim(p_name), 'address', trim(p_address), 'category', trim(p_category),
      'room_count', p_room_count, 'latitude', p_latitude, 'longitude', p_longitude)));
end;
$$;

-- 9) ADMIN-07 가상 후원 예산 -------------------------------------------------------
create function public.admin_list_sponsors()
returns table (id bigint, name text, description text, starts_on date, ends_on date, active boolean,
  budget integer, paid integer, remaining integer, created_at timestamptz)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  today date := (now() at time zone 'Asia/Seoul')::date;
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 볼 수 있어요.' using errcode = '42501';
  end if;
  return query
    select s.id, s.name, s.description, s.starts_on, s.ends_on, today between s.starts_on and s.ends_on,
      t.budget, t.paid, t.budget - t.paid, s.created_at
    from public.sponsors s
    cross join lateral (
      select coalesce(sum(x.amount) filter (where x.kind = 'budget'), 0)::integer as budget,
             coalesce(sum(x.amount) filter (where x.kind = 'payout'), 0)::integer as paid
      from public.sponsor_transactions x where x.sponsor_id = s.id
    ) t
    order by (today between s.starts_on and s.ends_on) desc, s.ends_on, s.id;
end;
$$;

-- 등록(p_sponsor_id = null) 또는 수정. 등록할 때 첫 예산을 함께 넣을 수 있다.
create function public.admin_save_sponsor(p_sponsor_id bigint, p_name text, p_description text,
  p_starts_on date, p_ends_on date, p_initial_budget integer default 0)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  saved_id bigint;
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 할 수 있어요.' using errcode = '42501';
  end if;
  if coalesce(trim(p_name), '') = '' or p_starts_on is null or p_ends_on is null then
    raise exception 'admin: 기업명과 후원 기간을 입력해 주세요.' using errcode = '22023';
  end if;
  if p_ends_on < p_starts_on then
    raise exception 'admin: 종료일이 시작일보다 빠를 수 없어요.' using errcode = '22023';
  end if;

  if p_sponsor_id is null then
    insert into public.sponsors (name, description, starts_on, ends_on)
    values (trim(p_name), coalesce(trim(p_description), ''), p_starts_on, p_ends_on)
    returning id into saved_id;
    if coalesce(p_initial_budget, 0) > 0 then
      insert into public.sponsor_transactions (sponsor_id, kind, amount, note, created_by)
      values (saved_id, 'budget', p_initial_budget, '첫 후원 예산', auth.uid());
    end if;
  else
    update public.sponsors
    set name = trim(p_name), description = coalesce(trim(p_description), ''), starts_on = p_starts_on, ends_on = p_ends_on
    where id = p_sponsor_id
    returning id into saved_id;
    if saved_id is null then
      raise exception 'admin: 후원 기업을 찾을 수 없어요.' using errcode = 'P0002';
    end if;
  end if;

  insert into public.admin_actions (admin_id, action, target_type, target_id, detail)
  values (auth.uid(), 'sponsor_save', 'sponsor', saved_id::text, jsonb_build_object(
    'name', trim(p_name), 'starts_on', p_starts_on, 'ends_on', p_ends_on, 'new', p_sponsor_id is null));
  return saved_id;
end;
$$;

-- 예산 추가(+) 또는 감액(-). 남은 예산보다 많이 줄일 수 없다.
create function public.admin_adjust_sponsor_budget(p_sponsor_id bigint, p_amount integer, p_note text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  remaining integer;
begin
  if not public.is_admin() then
    raise exception 'admin: 관리자만 할 수 있어요.' using errcode = '42501';
  end if;
  if p_amount is null or p_amount = 0 then
    raise exception 'admin: 조정할 포인트를 입력해 주세요.' using errcode = '22023';
  end if;
  perform 1 from public.sponsors where id = p_sponsor_id for update;
  if not found then
    raise exception 'admin: 후원 기업을 찾을 수 없어요.' using errcode = 'P0002';
  end if;
  select coalesce(sum(amount) filter (where kind = 'budget'), 0) - coalesce(sum(amount) filter (where kind = 'payout'), 0)
  into remaining from public.sponsor_transactions where sponsor_id = p_sponsor_id;
  if remaining + p_amount < 0 then
    raise exception 'admin: 남은 예산(%P)보다 많이 줄일 수 없어요.', remaining using errcode = 'P0001';
  end if;

  insert into public.sponsor_transactions (sponsor_id, kind, amount, note, created_by)
  values (p_sponsor_id, 'budget', p_amount, coalesce(left(trim(p_note), 200), ''), auth.uid());
  insert into public.admin_actions (admin_id, action, target_type, target_id, detail)
  values (auth.uid(), 'sponsor_budget', 'sponsor', p_sponsor_id::text, jsonb_build_object('amount', p_amount, 'note', p_note));
end;
$$;

