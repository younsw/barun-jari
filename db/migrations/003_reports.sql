-- 003: 오류 신고 게시판

create table public.reports (
  id          bigint generated by default as identity primary key,
  user_id     uuid   not null default auth.uid() references public.users (id) on delete cascade,
  facility_id bigint not null references public.smoking_facilities (id) on delete cascade,
  type        text   not null check (type in ('closed', 'wrong_location', 'wrong_info', 'etc')),
  content     text   not null check (char_length(content) between 1 and 1000),
  status      text   not null default 'received'
              check (status in ('received', 'reviewing', 'accepted', 'rejected')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index reports_user_idx on public.reports (user_id, created_at desc);
create index reports_status_idx on public.reports (status, created_at);

create function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger reports_touch_updated_at
  before update on public.reports
  for each row execute function public.touch_updated_at();

-- 권한: 성인 인증한 회원만 신고 작성, 내 신고만 보기, 상태 변경은 관리자만
alter table public.reports enable row level security;

create policy "reports: 인증 회원 신고 작성" on public.reports
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and status = 'received'
    and exists (select 1 from public.users where id = auth.uid() and is_adult_verified)
  );

create policy "reports: 내 신고 또는 관리자 조회" on public.reports
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

create policy "reports: 관리자 상태 변경" on public.reports
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

revoke update on public.reports from anon, authenticated;
grant update (status) on public.reports to authenticated;
